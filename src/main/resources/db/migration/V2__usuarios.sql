CREATE TABLE usuario (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 run VARCHAR(15) NOT NULL, nombre VARCHAR(50) NOT NULL, apellidos VARCHAR(100) NOT NULL,
 correo VARCHAR(100) NOT NULL, contrasena_hash VARCHAR(255) NOT NULL,
 fecha_nacimiento DATE NOT NULL, region VARCHAR(255) NOT NULL, comuna VARCHAR(255) NOT NULL,
 direccion VARCHAR(300) NOT NULL, tipo VARCHAR(20) NOT NULL DEFAULT 'CLIENTE',
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT uk_usuario_run UNIQUE(run), CONSTRAINT uk_usuario_correo UNIQUE(correo),
 CONSTRAINT chk_usuario_tipo CHECK(tipo IN ('ADMINISTRADOR','VENDEDOR','CLIENTE'))
) ENGINE=InnoDB;
